/**
 * The shared species base: one row per species the map and forecast model, taken from the species guide (its index
 * rows and species files), so the map, the forecast and the guide say the same thing about a fish. Pure: the caller
 * hands in the guide data. `scripts/species-base.ts` writes the result to src/species/base.gen.ts, and
 * base.test.ts fails when the guide changes and the file was not rebuilt.
 *
 * Today a row carries what the warnings need: the guide page, the names, the edible rating, and the ciguatera size
 * advice (the guide's research/cigua-size: a published limit, our estimate, none known, or "do not eat").
 */

export type Edible = 'yes' | 'caution' | 'toxic' | 'no' | 'protected';
export interface CiguaRow {
  /** published: a sale limit or test result; estimate: the research's estimate; none: no size known; never: do not eat at any size. */
  basis: 'published' | 'estimate' | 'none' | 'never';
  /** Keep fish under this length (cm) and weight (kg) for lower risk, not safety. */
  cm?: number;
  kg?: number;
}
export interface BaseRow {
  /** The guide page id (#guide/all/<id>). */
  id: string;
  sci: string;
  en: string;
  es: string;
  edible?: Edible;
  /** The guide lists ciguatera among its food risks (or rates it toxic). */
  cigua: boolean;
  /** Size to keep for lower ciguatera risk, when the guide gives one. */
  size?: CiguaRow;
}

/** What the builder reads from the guide: its index rows and one species file by id. */
export interface GuideIndexRow { id: string; sci: string; en?: string[]; es?: string[]; edible?: string }
export interface GuideSpecies { edible?: string; eat?: { risks?: string[]; ciguaSize?: { basis: 'published' | 'estimate' | 'none'; maxKg?: number; maxCm?: number } } }

/** One row per scientific name in `taxa` (kind -> binomials), keyed by the scientific name. Names missing from the guide are skipped. */
export function buildBase(taxa: Readonly<Record<string, readonly string[]>>, index: readonly GuideIndexRow[], sp: (id: string) => GuideSpecies | null): Record<string, BaseRow> {
  const bySci = new Map(index.map((r) => [r.sci.toLowerCase(), r]));
  const out: Record<string, BaseRow> = {};
  const scis = [...new Set(Object.values(taxa).flat())].sort();
  for (const sci of scis) {
    const r = bySci.get(sci.toLowerCase());
    if (!r) continue;
    const f = sp(r.id);
    const risks = f?.eat?.risks ?? [];
    const edible = (f?.edible ?? r.edible) as Edible | undefined;
    const row: BaseRow = { id: r.id, sci: r.sci, en: r.en?.[0] ?? r.sci, es: r.es?.[0] ?? r.en?.[0] ?? r.sci, cigua: risks.includes('ciguatera') || edible === 'toxic' };
    if (edible) row.edible = edible;
    const c = f?.eat?.ciguaSize;
    if (c) {
      // A published basis with no size is a sale ban at any weight (tiger grouper in Cuba): do not eat.
      const basis = c.basis === 'published' && !c.maxCm && !c.maxKg ? 'never' : c.basis;
      row.size = { basis, ...(c.maxCm ? { cm: c.maxCm } : {}), ...(c.maxKg ? { kg: c.maxKg } : {}) };
    }
    out[r.sci] = row;
  }
  return out;
}

/** The generated module's text. */
export function baseModule(base: Record<string, BaseRow>): string {
  const rows = Object.values(base).map((r) => `  ${JSON.stringify(r.sci)}: ${JSON.stringify(r)},`).join('\n');
  return `// GENERATED by scripts/species-base.ts from the species guide (public/data/guide). Do not edit: run \`npm run data:base\`.
import type { BaseRow } from './build';

export const BASE: Readonly<Record<string, BaseRow>> = {
${rows}
};
`;
}
